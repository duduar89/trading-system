  CONSTRAINT pausa_orden CHECK (ventana_inicio < ventana_fin),
  CONSTRAINT pausa_profesional FOREIGN KEY (profesional_id) REFERENCES profesionales (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS pausa_profesional_idx ON pausas (profesional_id);
CREATE OR REPLACE TRIGGER pausas_avanzar_id AFTER INSERT ON pausas REFERENCING NEW TABLE AS nuevas FOR EACH STATEMENT EXECUTE FUNCTION avanzar_identidad();

