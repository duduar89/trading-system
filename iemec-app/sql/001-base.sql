-- 001 · Base de la clínica: datos, horario, festivos, salas, equipos, profesionales, catálogo de
-- tratamientos, pacientes, consentimientos, personal de la app, registro de hechos, cola y candados.
--
-- PostgreSQL (el de Supabase y el del portátil). Lo que viene de la época de MariaDB, y cómo queda:
--   · Todas las fechas y horas son TIMESTAMPTZ: instantes absolutos, que db.js manda y lee en UTC (la
--     hora de Madrid se calcula en el motor). Un día suelto es DATE y la hora del reloj, TIME.
--   · Los ENUM son TEXT con un CHECK (col IN (…)); un valor nuevo se añade cambiando ese CHECK.
--   · El JSON es TEXT con un CHECK de que es JSON válido, igual que era en MariaDB; db.js lo devuelve
--     como texto y el código hace JSON.parse.
--   · Los UNSIGNED llevan CHECK (col >= 0) donde importa (contadores, duraciones, intentos).
--   · Los ids son GENERATED BY DEFAULT AS IDENTITY: se pueden poner a mano (las semillas y las pruebas
--     lo hacen) y, como el AUTO_INCREMENT de MariaDB, el siguiente salta por encima del mayor que se
--     puso (avanzar_identidad, abajo).
--   · MariaDB comparaba texto sin distinguir mayúsculas ni tildes; PostgreSQL sí las distingue. Qué se
--     hace con cada columna (emails con lower(), códigos exactos…): docs/PORTE-POSTGRES.md.
--   · Los índices llevan un nombre único en todo el esquema (en PostgreSQL comparten espacio con las
--     tablas). MariaDB creaba sola un índice por cada clave ajena; aquí van escritos, con el sufijo _idx.

-- ON UPDATE CURRENT_TIMESTAMP de MariaDB: actualizado_en se pone a la hora de la transacción cuando
-- cambia cualquier otra columna de la fila (si el UPDATE no cambia nada, o él mismo fija
-- actualizado_en, se deja como está). Las pruebas la sustituyen por la del reloj falso (test/ayuda-bd.js).
CREATE OR REPLACE FUNCTION set_actualizado_en() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.actualizado_en IS NOT DISTINCT FROM OLD.actualizado_en AND ROW(NEW.*) IS DISTINCT FROM ROW(OLD.*) THEN
    NEW.actualizado_en := now();
  END IF;
  RETURN NEW;
END
$$;

-- El AUTO_INCREMENT de MariaDB salta por encima de un id puesto a mano; la identidad de PostgreSQL no
-- (el siguiente id automático chocaría con el que se puso). Este disparador, uno por tabla con
-- identidad, y por sentencia (no por fila), sube la secuencia hasta el mayor id insertado.
CREATE OR REPLACE FUNCTION avanzar_identidad() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  secuencia regclass := pg_get_serial_sequence(format('%I.%I', TG_TABLE_SCHEMA, TG_TABLE_NAME), 'id')::regclass;
  mayor bigint;
BEGIN
  SELECT max(id) INTO mayor FROM nuevas;
  IF mayor IS NOT NULL AND mayor > COALESCE(pg_sequence_last_value(secuencia), 0) THEN
    PERFORM setval(secuencia, mayor);
  END IF;
  RETURN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS clinica (
  id SMALLINT PRIMARY KEY DEFAULT 1,
  nombre VARCHAR(120) NOT NULL,
  nombre_corto VARCHAR(40) NOT NULL,
  razon_social VARCHAR(160),
  nif VARCHAR(20),
  direccion VARCHAR(200),
  cp VARCHAR(10),
  municipio VARCHAR(80),
  provincia VARCHAR(80),
  telefono VARCHAR(20),
  whatsapp VARCHAR(20),
  email VARCHAR(160),
  web VARCHAR(160),
  zona_horaria VARCHAR(40) NOT NULL DEFAULT 'Europe/Madrid',
  lat NUMERIC(9,6),
  lng NUMERIC(9,6),
  google_place_id VARCHAR(120),
  paso_agenda_min SMALLINT NOT NULL DEFAULT 5,
  retencion_hueco_min INTEGER NOT NULL DEFAULT 15,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT clinica_paso_agenda_min_pos CHECK (paso_agenda_min >= 0),
  CONSTRAINT clinica_retencion_hueco_min_pos CHECK (retencion_hueco_min >= 0),
  CONSTRAINT clinica_una_fila CHECK (id = 1)
);
CREATE OR REPLACE TRIGGER clinica_actualizado BEFORE UPDATE ON clinica FOR EACH ROW EXECUTE FUNCTION set_actualizado_en();

-- Horario de apertura por día de la semana (1 = lunes … 7 = domingo). Varias filas = jornada partida.
CREATE TABLE IF NOT EXISTS horario_clinica (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia_semana SMALLINT NOT NULL,
  abre TIME NOT NULL,
  cierra TIME NOT NULL,
  CONSTRAINT horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
  CONSTRAINT horario_orden CHECK (abre < cierra)
);
CREATE UNIQUE INDEX IF NOT EXISTS horario_unico ON horario_clinica (dia_semana, abre);
CREATE OR REPLACE TRIGGER horario_clinica_avanzar_id AFTER INSERT ON horario_clinica REFERENCING NEW TABLE AS nuevas FOR EACH STATEMENT EXECUTE FUNCTION avanzar_identidad();

