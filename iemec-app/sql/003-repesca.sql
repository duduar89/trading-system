-- Los seguimientos con fecha: la «memoria» de la repesca vive aquí, no en la IA.
CREATE TABLE IF NOT EXISTS seguimientos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER,
  lead_id INTEGER,
  conversacion_id INTEGER,
  contexto TEXT NOT NULL DEFAULT 'general',
  contexto_id INTEGER,
  motivo VARCHAR(40) NOT NULL,
  plazo_tipo VARCHAR(30),
  frase_cifrada BYTEA,
  frase_iv BYTEA,
  frase_tag BYTEA,
  programado_para TIMESTAMPTZ NOT NULL,
  estado TEXT NOT NULL DEFAULT 'pendiente',
  creado_por TEXT NOT NULL DEFAULT 'ia',
  usuario_id SMALLINT,
  intentos SMALLINT NOT NULL DEFAULT 0,
  plantilla_uso VARCHAR(40) NOT NULL DEFAULT 'como_quedamos',
  resultado VARCHAR(160),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT seguimientos_contexto_chk CHECK (contexto IN ('lead','cancelacion','presupuesto','toca_repetir','dormido','vale_regalo','cita','general')),
  CONSTRAINT seguimientos_frase_iv_len CHECK (octet_length(frase_iv) <= 16),
  CONSTRAINT seguimientos_frase_tag_len CHECK (octet_length(frase_tag) <= 16),
  CONSTRAINT seguimientos_estado_chk CHECK (estado IN ('pendiente','enviado','cancelado','cumplido','fallido')),
  CONSTRAINT seguimientos_creado_por_chk CHECK (creado_por IN ('ia','persona','sistema')),
  CONSTRAINT seguimientos_intentos_pos CHECK (intentos >= 0),
  CONSTRAINT seg_paciente_fk FOREIGN KEY (paciente_id) REFERENCES pacientes (id) ON DELETE CASCADE,
  CONSTRAINT seg_conv_fk FOREIGN KEY (conversacion_id) REFERENCES conversaciones (id) ON DELETE SET NULL
