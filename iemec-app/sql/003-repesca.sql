CREATE TABLE IF NOT EXISTS leads (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER,
  telefono VARCHAR(20),
  nombre VARCHAR(120),
  email VARCHAR(160),
  origen TEXT NOT NULL,
  campana VARCHAR(160),
  conjunto VARCHAR(160),
  anuncio VARCHAR(160),
  anuncio_id VARCHAR(60),
  ctwa_clid VARCHAR(120),
  codigo_web VARCHAR(40),
  utm TEXT,
  tratamiento_interes_id VARCHAR(80),
  texto_inicial VARCHAR(600),
  etapa TEXT NOT NULL DEFAULT 'nuevo',
  motivo_perdida VARCHAR(40),
  ghl_contact_id VARCHAR(60),
  ghl_opportunity_id VARCHAR(60),
  id_externo VARCHAR(120),
  cita_id INTEGER,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  primer_contacto_en TIMESTAMPTZ,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT leads_origen_chk CHECK (origen IN ('meta_formulario','meta_ctwa','web_whatsapp','ghl','treatwell','telefono','recepcion','google','referido','otro')),
  CONSTRAINT leads_utm_json CHECK (utm IS NULL OR utm::jsonb IS NOT NULL),
  CONSTRAINT leads_etapa_chk CHECK (etapa IN ('nuevo','contactado','conversando','cita','asistio','vendido','perdido')),
  CONSTRAINT lead_paciente_fk FOREIGN KEY (paciente_id) REFERENCES pacientes (id) ON DELETE SET NULL,
  CONSTRAINT lead_trat_fk FOREIGN KEY (tratamiento_interes_id) REFERENCES tratamientos (id) ON DELETE SET NULL,
  CONSTRAINT lead_cita_fk FOREIGN KEY (cita_id) REFERENCES citas (id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS lead_externo ON leads (origen, id_externo);
CREATE INDEX IF NOT EXISTS lead_etapa ON leads (etapa, creado_en);
CREATE INDEX IF NOT EXISTS lead_paciente ON leads (paciente_id);
CREATE INDEX IF NOT EXISTS lead_trat_fk_idx ON leads (tratamiento_interes_id);
CREATE INDEX IF NOT EXISTS lead_cita_fk_idx ON leads (cita_id);
CREATE OR REPLACE TRIGGER leads_avanzar_id AFTER INSERT ON leads REFERENCING NEW TABLE AS nuevas FOR EACH STATEMENT EXECUTE FUNCTION avanzar_identidad();
CREATE OR REPLACE TRIGGER leads_actualizado BEFORE UPDATE ON leads FOR EACH ROW EXECUTE FUNCTION set_actualizado_en();

