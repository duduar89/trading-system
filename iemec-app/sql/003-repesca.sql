-- El texto va cifrado (AES-256-GCM) con la clave del servidor; en la base solo hay bytes.
CREATE TABLE IF NOT EXISTS mensajes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversacion_id INTEGER NOT NULL,
  direccion TEXT NOT NULL,
  autor TEXT NOT NULL,
  usuario_id SMALLINT,
  tipo TEXT NOT NULL DEFAULT 'texto',
  cuerpo_cifrado BYTEA,
  iv BYTEA,
  tag BYTEA,
  plantilla_id INTEGER,
  wa_id VARCHAR(120),
  estado TEXT NOT NULL DEFAULT 'pendiente',
  error_codigo VARCHAR(20),
  error_texto VARCHAR(255),
  coste_eur NUMERIC(7,4),
  intencion VARCHAR(40),
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT mensajes_direccion_chk CHECK (direccion IN ('entrante','saliente')),
  CONSTRAINT mensajes_autor_chk CHECK (autor IN ('paciente','ia','persona','sistema')),
  CONSTRAINT mensajes_tipo_chk CHECK (tipo IN ('texto','plantilla','audio','imagen','documento','boton','interactivo','sistema')),
  CONSTRAINT mensajes_iv_len CHECK (octet_length(iv) <= 16),
  CONSTRAINT mensajes_tag_len CHECK (octet_length(tag) <= 16),
  CONSTRAINT mensajes_estado_chk CHECK (estado IN ('pendiente','enviado','entregado','leido','fallido','recibido')),
  CONSTRAINT msg_conv_fk FOREIGN KEY (conversacion_id) REFERENCES conversaciones (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS msg_wa ON mensajes (wa_id);
CREATE INDEX IF NOT EXISTS msg_conv ON mensajes (conversacion_id, creado_en);
CREATE OR REPLACE TRIGGER mensajes_avanzar_id AFTER INSERT ON mensajes REFERENCING NEW TABLE AS nuevas FOR EACH STATEMENT EXECUTE FUNCTION avanzar_identidad();

